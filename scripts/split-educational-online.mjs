/** Generate SQL Editor-sized installation steps without changing the canonical migration. */
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const marker='-- GENERATED by scripts/split-educational-online.mjs; do not edit this generated file.';
const seedBlock=/-- BEGIN EDUCATIONAL SEED[\s\S]*?-- END EDUCATIONAL SEED/;
const byteSize=sql=>Buffer.byteLength(sql,'utf8');
const pad=n=>String(n).padStart(2,'0');
const taggedJson=(value,tag)=>{const json=JSON.stringify(value);if(json.includes(`$${tag}$`))throw Error(`SQL delimiter collision: ${tag}`);return `$${tag}$${json}$${tag}$::jsonb`;};

export function parseEducationalMigration(source){
 const block=source.match(seedBlock)?.[0];
 const json=block?.match(/\$edu_seed\$([\s\S]*?)\$edu_seed\$/)?.[1];
 if(!block||!json)throw Error('Expected the canonical EDUCATIONAL SEED block in migration 005');
 const rows=JSON.parse(json);
 if(!Array.isArray(rows)||!rows.length)throw Error('The canonical educational seed must contain records');
 const grouped=new Map();const keys=new Set();
 for(const row of rows){
  assert.deepEqual(Object.keys(row).sort(),['data','game','id','lesson_id','unit_id']);
  if(!Number.isInteger(row.game)||row.game<0||row.game>12||!row.data||row.id!==row.data.id||row.unit_id!==row.data.unit_id||row.lesson_id!==row.data.lesson_id)throw Error('Invalid canonical activity row');
  const key=`${row.game}:${row.id}`;if(keys.has(key))throw Error(`Duplicate canonical activity key: ${key}`);keys.add(key);
  const data={...row.data};delete data.term;
  let item=grouped.get(row.id);
  if(item)assert.deepEqual(item.data,data,`Conflicting canonical content for ${row.id}`);
  else{item={data,uses:[]};grouped.set(row.id,item);}
  item.uses.push(Object.hasOwn(row.data,'term')?[row.game,row.data.term]:[row.game]);
 }
 return {rows,groups:[...grouped.values()]};
}

function contentSql(groups,index,total){
 const count=groups.reduce((n,x)=>n+x.uses.length,0);
 return `${marker}
-- Content part ${pad(index)} of ${pad(total)}: ${count} activity rows; run AFTER 00_schema.sql.
-- Each file is one independent transaction. Safe to run the same file again.
begin;
insert into school_private.educational_questions(game,id,unit_id,lesson_id,data)
select (use->>0)::int,item->'data'->>'id',item->'data'->>'unit_id',item->'data'->>'lesson_id',
 (item->'data') || case when jsonb_array_length(use)>1 then jsonb_build_object('term',use->1) else '{}'::jsonb end
from jsonb_array_elements(${taggedJson(groups,'educational_content')}) item
cross join lateral jsonb_array_elements(item->'uses') use
on conflict(game,id) do update set data=excluded.data,unit_id=excluded.unit_id,lesson_id=excluded.lesson_id;
commit;
`;
}

function verificationSql(groups,rowCount){
 const expected=groups.map(x=>({id:x.data.id,games:x.uses.map(use=>use[0])}));
 return `${marker}
-- Run LAST, after every content part. Read-only checks; no user data changes.
do $educational_verify$
declare missing_rows integer;
begin
 if to_regprocedure('public.educational_duel_create(integer,text,text,integer)') is null
  or to_regprocedure('public.educational_duel_finish(uuid)') is null
  or to_regprocedure('school_private.educational_answer(uuid,uuid,text,jsonb)') is null then
  raise exception 'Installation incomplete: run 00_schema.sql first';
 end if;
 select count(*)::int into missing_rows
 from jsonb_array_elements(${taggedJson(expected,'educational_expected')}) expected
 cross join lateral jsonb_array_elements_text(expected->'games') game
 left join school_private.educational_questions installed on installed.id=expected->>'id' and installed.game=game::int
 where installed.id is null;
 if missing_rows<>0 then
  raise exception 'Installation incomplete: % required activity rows are missing. Run all content files, then run 99_verify.sql again.',missing_rows;
 end if;
 if not exists(select 1 from pg_class where oid='school_private.educational_questions'::regclass and relrowsecurity)
  or not exists(select 1 from pg_class where oid='school_private.educational_finishes'::regclass and relrowsecurity) then
  raise exception 'Installation incomplete: expected row level security is not enabled';
 end if;
 if not has_function_privilege('authenticated','public.educational_duel_create(integer,text,text,integer)','EXECUTE')
  or not has_function_privilege('authenticated','public.educational_duel_finish(uuid)','EXECUTE')
  or has_function_privilege('anon','public.educational_duel_create(integer,text,text,integer)','EXECUTE')
  or has_function_privilege('anon','public.educational_duel_finish(uuid)','EXECUTE')
  or has_function_privilege('authenticated','school_private.educational_answer(uuid,uuid,text,jsonb)','EXECUTE') then
  raise exception 'Installation incomplete: unexpected activity function privileges';
 end if;
 if has_table_privilege('authenticated','school_private.educational_questions','SELECT,INSERT,UPDATE,DELETE')
  or has_table_privilege('authenticated','school_private.educational_finishes','SELECT,INSERT,UPDATE,DELETE')
  or has_table_privilege('anon','school_private.educational_questions','SELECT,INSERT,UPDATE,DELETE')
  or has_table_privilege('anon','school_private.educational_finishes','SELECT,INSERT,UPDATE,DELETE') then
  raise exception 'Installation incomplete: unexpected direct activity table privileges';
 end if;
end;
$educational_verify$;
select 'ready' as educational_online_status,${rowCount} as required_activity_rows_verified;
`;
}

export function buildEditorParts(source,{maxBytes=60000}={}){
 if(!Number.isInteger(maxBytes)||maxBytes<1000)throw Error('Invalid SQL Editor byte limit');
 const {rows,groups}=parseEducationalMigration(source);
 const schema=`${marker}\n-- Step 00: schema and functions only. Run all numbered content files next, then 99_verify.sql.\n${source.replace(seedBlock,'-- Content is installed separately by the numbered content files.')}\n`;
 const chunks=[];let chunk=[];
 for(const group of groups){
  if(byteSize(contentSql([group],99,99))>maxBytes)throw Error(`Canonical question ${group.data.id} exceeds the SQL Editor part limit`);
  if(chunk.length&&byteSize(contentSql([...chunk,group],99,99))>maxBytes){chunks.push(chunk);chunk=[];}
  chunk.push(group);
 }
 if(chunk.length)chunks.push(chunk);
 if(chunks.length>98)throw Error('Too many SQL Editor parts for the two-digit filenames');
 const parts=[{name:'00_schema.sql',kind:'schema',sql:schema},...chunks.map((group,index)=>({name:`${pad(index+1)}_content.sql`,kind:'content',rows:group.reduce((n,x)=>n+x.uses.length,0),sql:contentSql(group,index+1,chunks.length)})),{name:'99_verify.sql',kind:'verify',sql:verificationSql(groups,rows.length)}];
 for(const part of parts){part.bytes=byteSize(part.sql);if(part.bytes>maxBytes)throw Error(`${part.name} exceeds ${maxBytes} bytes (${part.bytes})`);}
 return {parts,rowCount:rows.length,uniqueQuestionCount:groups.length};
}

export async function writeEditorParts({root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),maxBytes=60000}={}){
 const source=await fs.readFile(path.join(root,'supabase/migrations/005_educational_online.sql'),'utf8');
 const result=buildEditorParts(source,{maxBytes});
 const output=path.join(root,'supabase/sql-editor/005');await fs.mkdir(output,{recursive:true});
 const names=new Set(result.parts.map(part=>part.name));
 for(const item of await fs.readdir(output,{withFileTypes:true})){
  if(!item.isFile()||!/^\d{2}_(schema|content|verify)\.sql$/.test(item.name)||names.has(item.name))continue;
  const target=path.join(output,item.name),existing=await fs.readFile(target,'utf8');
  if(!existing.startsWith(marker))throw Error(`Refusing to remove unrecognized file: ${target}`);
  await fs.unlink(target);
 }
 for(const part of result.parts)await fs.writeFile(path.join(output,part.name),part.sql);
 return result;
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const result=await writeEditorParts();
 console.log(JSON.stringify({directory:'supabase/sql-editor/005',rowCount:result.rowCount,uniqueQuestionCount:result.uniqueQuestionCount,parts:result.parts.map(({name,bytes,rows})=>({name,bytes,...rows===undefined?{}:{rows}}))},null,2));
}
